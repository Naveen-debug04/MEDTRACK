const express = require('express');
const assistant = require('../controllers/assistantController');
const audit = require('../controllers/auditController');
const appointments = require('../controllers/appointmentController');
const batches = require('../controllers/batchController');
const dashboard = require('../controllers/dashboardController');
const medicines = require('../controllers/medicineController');
const notifications = require('../controllers/notificationController');
const reports = require('../controllers/reportController');
const settings = require('../controllers/settingsController');
const members = require('../controllers/memberController');
const { requireOwner } = require('../middleware/requireAuth');
const { asyncHandler } = require('../utils/http');

const router = express.Router();
router.get('/appointments', asyncHandler(appointments.list));
router.post('/appointments', asyncHandler(appointments.create));
router.patch('/appointments/:id/status', asyncHandler(appointments.updateStatus));
router.delete('/appointments/:id', asyncHandler(appointments.remove));
router.get('/dashboard', asyncHandler(dashboard.dashboard));
router.get('/settings', asyncHandler(settings.getSettings));
router.patch('/settings', requireOwner, asyncHandler(settings.updateSettings));
router.get('/members', requireOwner, asyncHandler(members.listMembers));
router.post('/members/invitations', requireOwner, asyncHandler(members.createInvitation));
router.delete('/members/invitations/:id', requireOwner, asyncHandler(members.revokeInvitation));
router.delete('/members/:id', requireOwner, asyncHandler(members.removeMember));
router.get('/medicines', asyncHandler(medicines.list));
router.post('/medicines', asyncHandler(medicines.create));
router.patch('/medicines/:id', asyncHandler(medicines.update));
router.delete('/medicines/:id', asyncHandler(medicines.remove));
router.get('/batches', asyncHandler(batches.list));
router.post('/batches', asyncHandler(batches.create));
router.patch('/batches/:id/stock', asyncHandler(batches.updateStock));
router.delete('/batches/:id', asyncHandler(batches.remove));
router.get('/notifications', asyncHandler(notifications.list));
router.patch('/notifications/:id/read', asyncHandler(notifications.markRead));
router.get('/audit', asyncHandler(audit.list));
router.get('/reports/inventory', asyncHandler(reports.inventoryReport));
router.post('/assistant', asyncHandler(assistant.ask));

module.exports = router;
